"""Generates lib/core/icons/phosphor.dart from the phosphor_flutter package's duotone icon list.

The package's Dart classes extend IconData, which Flutter 3.47 made final, so they no longer
compile. Its fonts still ship with the package, so this writes plain const IconData values for
them under the package's own names. Only icons used under lib/ are written, which keeps icon
tree shaking effective.

Usage: python -I tool/gen_phosphor_icons.py <path to phosphor_flutter-2.1.0>
"""
import pathlib
import re
import sys

package = pathlib.Path(sys.argv[1])
root = pathlib.Path(__file__).resolve().parent.parent
source = (package / 'lib/src/phosphor_icons_duotone.dart').read_text(encoding='utf-8')
icons = dict(
    (name, (int(primary, 16), int(secondary, 16)))
    for name, primary, secondary in re.findall(
        r'static const (\w+) = PhosphorDuotoneIconData\(\s*(0x[0-9a-f]+),\s*PhosphorIconData\((0x[0-9a-f]+)',
        source,
    )
)
out_path = root / 'lib/core/icons/phosphor.dart'
used = set()
for path in (root / 'lib').rglob('*.dart'):
    if path == out_path:
        continue
    used.update(re.findall(r'PhosphorIconsDuotone\.(\w+)', path.read_text(encoding='utf-8')))
missing = sorted(used - icons.keys())
if missing:
    sys.exit(f'Unknown Phosphor duotone icons: {missing}')

lines = [
    '// Generated by tool/gen_phosphor_icons.py. Do not edit by hand; rerun it after using a new icon.',
    '//',
    '// Phosphor duotone icons (MIT License, Phosphor Icons), drawn with the PhosphorDuotone font that',
    '// the phosphor_flutter package bundles. The package\'s own classes extend IconData, which Flutter',
    '// 3.47 made final, so they no longer compile. This file provides the same names over plain IconData.',
    "import 'package:flutter/widgets.dart';",
    '',
    '/// A Phosphor icon: plain [IconData] in the duotone font.',
    'typedef PhosphorIconData = IconData;',
    '',
    'const _family = \'PhosphorDuotone\';',
    'const _package = \'phosphor_flutter\';',
    '',
    'abstract final class PhosphorIconsDuotone {',
]
for name in sorted(used):
    primary, _ = icons[name]
    lines += [
        f'  static const {name} = IconData(',
        f'    0x{primary:x},',
        '    fontFamily: _family,',
        '    fontPackage: _package,',
        '    matchTextDirection: true,',
        '  );',
    ]
lines += [
    '}',
    '',
    '/// The faint second layer of each duotone icon, keyed by the icon\'s code point.',
    'const _secondary = <int, IconData>{',
]
for name in sorted(used):
    primary, secondary = icons[name]
    lines += [
        f'  0x{primary:x}: IconData(',
        f'    0x{secondary:x},',
        '    fontFamily: _family,',
        '    fontPackage: _package,',
        '    matchTextDirection: true,',
        '  ),',
    ]
lines += [
    '};',
    '',
    '/// Draws a duotone icon: its second layer at [duotoneSecondaryOpacity] under the main glyph.',
    'class PhosphorIcon extends StatelessWidget {',
    '  const PhosphorIcon(',
    '    this.icon, {',
    '    super.key,',
    '    this.size,',
    '    this.color,',
    '    this.semanticLabel,',
    '    this.duotoneSecondaryOpacity = 0.20,',
    '    this.duotoneSecondaryColor,',
    '  });',
    '',
    '  final IconData icon;',
    '  final double? size;',
    '  final Color? color;',
    '  final String? semanticLabel;',
    '  final double duotoneSecondaryOpacity;',
    '  final Color? duotoneSecondaryColor;',
    '',
    '  @override',
    '  Widget build(BuildContext context) {',
    '    final main = Icon(icon, size: size, color: color, semanticLabel: semanticLabel);',
    '    final secondary = _secondary[icon.codePoint];',
    '    if (secondary == null || icon.fontFamily != _family) return main;',
    '    return Stack(',
    '      alignment: Alignment.center,',
    '      children: [',
    '        Opacity(',
    '          opacity: duotoneSecondaryOpacity,',
    '          child: Icon(secondary, size: size, color: duotoneSecondaryColor ?? color),',
    '        ),',
    '        main,',
    '      ],',
    '    );',
    '  }',
    '}',
    '',
]
out_path.parent.mkdir(parents=True, exist_ok=True)
out_path.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
print(f'wrote {len(used)} icons to {out_path.relative_to(root)}')
